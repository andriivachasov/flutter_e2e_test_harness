class ExecutorResult {
  ExecutorResult({
    required this.role,
    required this.passed,
    required this.timedOut,
    required this.aborted,
    required this.exitCode,
    required this.duration,
  });

  final String role;
  final bool passed;
  final bool timedOut;

  /// Killed by the orchestrator (environment failure), not a test verdict.
  final bool aborted;
  final int exitCode;
  final Duration duration;
}

class PatrolExecutor {
  PatrolExecutor(this.config);

  final HarnessConfig config;

  /// Writes `integration_test/test_bundle.dart` once per run, covering every
  /// test in the manifest, and makes every `patrol test` reuse it
  /// (`--no-generate-bundle`).
  ///
  /// Why: `patrol test` normally regenerates that single file from its
  /// `--target`. Two shards building different tests concurrently in the
  /// same app dir therefore overwrite each other's bundle and end up running
  /// the wrong test. Our bundle is identical for every shard; the test to
  /// run is chosen at compile time by the `E2E_TEST_ID` dart-define each
  /// shard already gets, so each build still contains exactly one test.
  /// Without the define (a manual `patrol test`), every test is registered.
  ///
  /// The body mirrors patrol_cli 4.6.1's TestBundler template (pinned).
  void prepareBundle(List<TestSpec> allTests) {
    final appDir = config.resolve(config.appDir);
    // patrol_cli writes and compiles `<patrol.test_directory>/test_bundle.dart`
    // (pubspec `patrol:` section; default `patrol_test`, NOT
    // integration_test). Writing anywhere else is silently ignored.
    final testDir = _patrolTestDirectory(appDir);
    final imports = StringBuffer();
    final groups = StringBuffer();
    for (final t in allTests) {
      final rel = t.target.startsWith('$testDir/')
          ? t.target.substring(testDir.length + 1)
          : '../${t.target}';
      final alias = _alias(rel);
      imports.writeln("import '$rel' as $alias;");
      groups.writeln("  if (_selected.isEmpty || _selected == '${t.name}') {");
      groups.writeln("    group('${alias.replaceAll('__', '.')}', $alias.main);");
      groups.writeln('  }');
    }
    File('$appDir/$testDir/test_bundle.dart')
      ..createSync(recursive: true)
      ..writeAsStringSync('''
// GENERATED by the e2e orchestrator (PatrolExecutor.prepareBundle) — DO NOT
// EDIT, DO NOT COMMIT. Mirrors patrol_cli's test bundle; the group for a
// test is registered only when E2E_TEST_ID selects it (or is unset).
// ignore_for_file: type=lint, invalid_use_of_internal_member

