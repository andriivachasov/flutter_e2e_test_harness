  /// `patrol.test_directory` from the app's pubspec.yaml (patrol_cli default
  /// `patrol_test`). A tiny hand parser keeps this file free of extra deps.
  static String _patrolTestDirectory(String appDir) {
    final pubspec = File('$appDir/pubspec.yaml');
    if (!pubspec.existsSync()) return 'patrol_test';
    var inPatrol = false;
    for (final line in pubspec.readAsLinesSync()) {
      if (RegExp(r'^patrol:\s*$').hasMatch(line)) {
        inPatrol = true;
        continue;
      }
      if (inPatrol && RegExp(r'^\S').hasMatch(line)) inPatrol = false;
      final m = RegExp(r'^\s+test_directory:\s*(\S+)').firstMatch(line);
      if (inPatrol && m != null) {
        return m.group(1)!.replaceAll(RegExp('["\']'), '');
      }
    }
    return 'patrol_test';
  }

  static String _alias(String relPath) {
    var name = relPath.endsWith('.dart')
        ? relPath.substring(0, relPath.length - 5)
        : relPath;
    while (name.startsWith('../')) {
      name = name.substring(3);
    }
    name = name.replaceAll('/', '__').replaceAll(RegExp('[^a-zA-Z0-9_]'), '_');
    return RegExp('[0-9]').hasMatch(name[0]) ? '_$name' : name;
  }

  /// Runs [spec] for one role on one device; patrol output goes to [testLog].
  ///
  /// [testServerPort] / [appServerPort] are Patrol's two internal
  /// test-runner<->app ports. They MUST be unique per concurrent role: iOS
  /// simulators share the host loopback, so two sessions on Patrol's
  /// defaults (8081/8082) — our two roles, or another project's simulator
  /// run on the same machine — silently connect to each other's apps.
  Future<ExecutorResult> runRole({
    required TestSpec spec,
    required RoleSpec role,
    required DeviceHandle device,
    required String runId,
    required int? backendPort,
    required int syncPort,
    required int testServerPort,
    required int appServerPort,
    required File testLog,
    Map<String, String> extraDefines = const {},
    Set<String> secretDefines = const {},
    Future<void>? abort,
  }) async {
    testLog.parent.createSync(recursive: true);
    final sink = testLog.openWrite();
    final started = DateTime.now();

    final defines = <String, String>{
      'E2E_RUN_ID': runId,
      'E2E_TEST_ID': spec.name,
      'E2E_ROLE': role.role,
      'E2E_PARTIES': '${spec.roles.length}',
      if (backendPort != null)
        'E2E_BACKEND_URL': 'http://${device.loopbackHost}:$backendPort',
      'E2E_SYNC_URL': 'http://${device.loopbackHost}:$syncPort',
      ...extraDefines,
    };

    final command = [
      'patrol',
      'test',
      '--target', spec.target,
      '--device', device.id,
      '--no-generate-bundle', // see prepareBundle
      '--test-server-port', '$testServerPort',
      '--app-server-port', '$appServerPort',
      for (final e in defines.entries) '--dart-define=${e.key}=${e.value}',
    ];
    // Never print secrets (R10 credentials travel only as defines): the
    // command line and every patrol/flutter/gradle line that echoes it get
    // the secret values replaced.
    final secretValues = [
      for (final key in secretDefines)
        if ((defines[key] ?? '').isNotEmpty) defines[key]!,
    ];
    String redact(String line) {
      var out = line;
      for (final v in secretValues) {
        out = out.replaceAll(v, '<redacted>');
      }
      return out;
    }
    sink.writeln('# ${redact(command.join(' '))}');

    final result = await runProc(
      command,
      cwd: config.resolve(config.appDir),
      timeout: config.testTimeout,
      onLine: (l) => sink.writeln(redact(l)),
      abort: abort,
    );
    if (result.aborted) sink.writeln('# aborted by orchestrator');
    if (result.timedOut) {
      sink.writeln('# killed: exceeded test timeout '
          '(${config.testTimeout.inSeconds}s)');
    }
    await sink.flush();
    await sink.close();

    return ExecutorResult(
      role: role.role,
      passed: result.ok,
      timedOut: result.timedOut,
      aborted: result.aborted,
      exitCode: result.exitCode,
      duration: DateTime.now().difference(started),
    );
  }
}
